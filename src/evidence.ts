import { createHash } from "node:crypto";
import { mkdir, open, writeFile, lstat } from "node:fs/promises";
import { join } from "node:path";
import { z } from "zod";
import { counts, RunSchema, type Run } from "./model.js";
const MAX_RUN = 32 * 1024 * 1024;
export const digest = (data: string) =>
  createHash("sha256").update(data).digest("hex");
const ManifestSchema = z
  .object({
    schema_version: z.literal("1"),
    run_id: z.string().uuid(),
    algorithm: z.literal("sha256"),
    files: z.record(z.string(), z.string().regex(/^[a-f0-9]{64}$/)),
  })
  .strict();
export async function boundedRead(
  path: string,
  max = MAX_RUN,
): Promise<string> {
  const info = await lstat(path);
  if (!info.isFile() || info.isSymbolicLink() || info.size > max)
    throw new Error("Evidence must be a bounded regular file");
  const handle = await open(path, "r");
  try {
    if (!(await handle.stat()).isFile())
      throw new Error("Evidence must be a regular file");
    const chunks: Buffer[] = [];
    let total = 0;
    while (total <= max) {
      const buffer = Buffer.alloc(Math.min(65536, max - total + 1));
      const { bytesRead } = await handle.read(buffer);
      if (!bytesRead) break;
      total += bytesRead;
      if (total > max) throw new Error("Evidence exceeds size limit");
      chunks.push(buffer.subarray(0, bytesRead));
    }
    return Buffer.concat(chunks).toString("utf8");
  } finally {
    await handle.close();
  }
}
export async function saveRun(run: Run, root: string): Promise<string> {
  RunSchema.parse(run);
  if (Buffer.byteLength(JSON.stringify(run, null, 2)) + 1 > MAX_RUN)
    throw new Error("Evidence exceeds run size budget");
  await mkdir(root, { recursive: true });
  const dir = join(root, run.run_id);
  await mkdir(dir);
  await mkdir(join(dir, "tests"));
  const files: Record<string, string> = {};
  const save = async (path: string, value: unknown) => {
    const data = JSON.stringify(value, null, 2) + "\n";
    files[path] = digest(data);
    await writeFile(join(dir, path), data, { flag: "wx", mode: 0o600 });
  };
  await save("run.json", run);
  await save("summary.json", {
    run_id: run.run_id,
    ...counts(run),
    notice: run.notice,
  });
  for (const result of run.results)
    await save(`tests/${result.definition.id}.json`, result);
  await writeFile(
    join(dir, "manifest.json"),
    JSON.stringify(
      { schema_version: "1", run_id: run.run_id, algorithm: "sha256", files },
      null,
      2,
    ) + "\n",
    { flag: "wx", mode: 0o600 },
  );
  return dir;
}
export async function loadRun(dir: string): Promise<Run> {
  if (
    !(await lstat(dir)).isDirectory() ||
    !(await lstat(join(dir, "tests"))).isDirectory()
  )
    throw new Error("Run must be a real evidence directory");
  const manifest = ManifestSchema.parse(
    JSON.parse(await boundedRead(join(dir, "manifest.json"), 65536)),
  );
  if (
    !manifest.files["run.json"] ||
    !manifest.files["summary.json"] ||
    Object.keys(manifest.files).length > 52
  )
    throw new Error("Incomplete manifest");
  let run: Run | undefined;
  for (const [path, expected] of Object.entries(manifest.files)) {
    if (!/^(run\.json|summary\.json|tests\/[A-Z]+-\d{3}\.json)$/.test(path))
      throw new Error("Unsafe manifest path");
    const data = await boundedRead(join(dir, path));
    if (digest(data) !== expected) throw new Error("Evidence hash mismatch");
    if (path === "run.json") run = RunSchema.parse(JSON.parse(data));
  }
  if (!run || run.run_id !== manifest.run_id)
    throw new Error("Evidence identity mismatch");
  for (const result of run.results) {
    const path = `tests/${result.definition.id}.json`;
    if (
      !manifest.files[path] ||
      JSON.stringify(JSON.parse(await boundedRead(join(dir, path)))) !==
        JSON.stringify(result)
    )
      throw new Error("Test evidence differs from run");
  }
  return run;
}
export function claim(run: Run) {
  const c = counts(run);
  return {
    label: "SELF-ASSERTED COMPATIBILITY CLAIM",
    status: "Compatibility Not Proven",
    notice:
      "This artifact is evidence generated by Flow Conformance Lab. It is not an official certification.",
    claim: {
      Implementation: `${run.config.implementation.name} ${run.config.implementation.version}`,
      "Protocol compatibility": `Jarvis ${run.protocol_version}; selected subset observed, full compatibility not proven`,
      "Conformance surface": `WorkSession/header/actor/replay subset; checklist at ${run.protocol_commit}; ${run.selected_tests.join(", ")}`,
      "Verification date": run.finished_at,
      Verifier: "self-attested",
      Evidence: `${run.run_id}/manifest.json`,
    },
    lab_evidence: {
      suite_version: run.suite_version,
      implementation_commit: run.config.implementation.commit ?? null,
      tests: c,
      selected_tests: run.selected_tests,
      evidence_id: run.run_id,
      limitations: run.limitations,
    },
  };
}
export function issue(run: Run, testId?: string): string {
  const failed = run.results.filter(
    (r) => r.status === "failed" && (!testId || r.definition.id === testId),
  );
  if (!failed.length) throw new Error("No matching failed tests");
  return failed
    .map(
      (r) =>
        `# Conformance Failure: ${r.definition.id} — ${r.definition.name}\n\n## Summary\n\n${r.definition.purpose}\n\n## Expected\n\n${r.diagnostic.expected}\n\n## Observed\n\n${r.diagnostic.observed}\n\n## Reproduction\n\n${r.diagnostic.reproduction.map((s, i) => `${i + 1}. ${s}`).join("\n")}\n\nReplay: run the CLI replay command with this evidence directory, an explicit target and the credential environment restored; use --test ${r.definition.id}.\n\n## Evidence\n\nRun: ${run.run_id}; exchanges: ${r.exchanges.length}; test file: tests/${r.definition.id}.json.\n\n## Protocol Reference\n\n${r.diagnostic.references.join("\n")}\n\n## Environment\n\nImplementation: ${run.config.implementation.name} ${run.config.implementation.version}; commit: ${run.config.implementation.commit ?? "not supplied"}\nProtocol: ${run.protocol_version} at ${run.protocol_commit}; suite: ${run.suite_version}; test: ${r.definition.version}\n\n## Confidence\n\n${r.diagnostic.confidence}; ${r.diagnostic.possible_causes.join(" ")}\n\n${run.notice}\n`,
    )
    .join("\n---\n\n");
}
